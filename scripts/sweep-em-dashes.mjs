// Remove every em-dash from the repo's text files. Written 2026-10-01 (Staci's
// house rule, widened from "public copy" to "everywhere").
//
//   node scripts/sweep-em-dashes.mjs           rewrite files in place
//   node scripts/sweep-em-dashes.mjs --check   list what is left, exit 1 if any
//
// How it decides what to do with each line (rule in scripts/lib/em-dash.mjs):
//   - Prose, comments, docs, copy:   rewritten with commas / colons / "to" / "|".
//   - Code that DETECTS or STRIPS an em-dash (card-title cleaners, test
//     assertions): the character becomes the escape: , so the code keeps
//     working and the file still holds no literal em-dash.
// Generated or third-party files are skipped (see SKIP below).
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { EM, deDash } from './lib/em-dash.mjs';

const CHECK = process.argv.includes('--check');

// Never touched: lockfile, build baselines (regenerated by `npm run parity`),
// binary/font/image assets, and this tool's own rule file.
const SKIP = [
  /^package-lock\.json$/,
  /^scripts\/\.parity\//,
  /\.(png|jpe?g|webp|avif|gif|ico|woff2?|ttf|otf|pdf|zip|mp4|mov)$/i,
];

// Files where some lines are code that works on the character itself.
const ESCAPE_FILES = [
  /\.test\.ts$/,
  /^src\/lib\/og-card\.ts$/,
  /^scripts\/patch-reid-design-2\.0.*\.mjs$/,
];
const isComment = (line) => /^\s*(\/\/|\*|\/\*|\{\/\*|<!--|#)/.test(line);
const isTestTitle = (line) => /^\s*(test|it|describe)(\.\w+)?\(/.test(line);

const files = execFileSync('git', ['ls-files', '-co', '--exclude-standard'], { encoding: 'utf8' })
  .split('\n')
  .filter(Boolean)
  .filter((f) => !SKIP.some((re) => re.test(f)));

let changedFiles = 0;
let remaining = 0;
for (const file of files) {
  let text;
  try {
    text = readFileSync(file, 'utf8');
  } catch {
    continue; // deleted in the working tree
  }
  if (!text.includes(EM)) continue;

  if (CHECK) {
    text.split('\n').forEach((l, i) => {
      if (l.includes(EM)) {
        remaining += 1;
        console.log(`${file}:${i + 1}: ${l.trim().slice(0, 120)}`);
      }
    });
    continue;
  }

  const escapeFile = ESCAPE_FILES.some((re) => re.test(file));
  const out = text
    .split('\n')
    .map((line) => {
      if (!line.includes(EM)) return line;
      if (escapeFile && !isComment(line) && !isTestTitle(line))
        return line.replaceAll(EM, '\\u2014');
      return deDash(line);
    })
    .join('\n');
  if (out !== text) {
    writeFileSync(file, out);
    changedFiles += 1;
  }
}

if (CHECK) {
  console.log(remaining ? `\n${remaining} line(s) still hold an em-dash.` : 'No em-dashes left.');
  process.exit(remaining ? 1 : 0);
}
console.log(`Rewrote ${changedFiles} file(s). Run with --check to confirm none are left.`);
