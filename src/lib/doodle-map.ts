// Safe to edit by hand
// =============================================================================
// Which doodles a page's sections get (2026-09-30, the ambient layer)
// =============================================================================
// A page gets at most MAX_DOODLES faint botanicals growing in from a corner,
// as background ambience, in the fine-line style of Staci's own Instagram
// drawings (src/scripts/ambient-doodles.ts places them). Until the 2026-09-30
// quiet pass EVERY content section got one; at that density they read as
// wallpaper, so now a page gets one near the top and one near the end
// (doodleSlots). This file decides WHICH sections and WHICH doodle each gets:
// the page's own first (PAGE_DOODLES), then the rest of the set in a fixed
// shuffle, never the same one twice in a row. Pure data and functions, unit
// tested in doodle-map.test.ts.
//
// The drawings are generated by `npm run doodles` (scripts/doodles.config.mjs)
// into src/assets/doodles/.
// =============================================================================

/** Every doodle the generator writes. Keep in step with scripts/doodles.config.mjs. */
export const DOODLE_NAMES = ['olive-sprig', 'eucalyptus', 'berry-sprig', 'leafy-stem'] as const;

export type DoodleName = (typeof DOODLE_NAMES)[number];

/**
 * First path segment -> the botanical a page's first section gets. The olive
 * sprig (her Instagram signature) opens Home and About; the rest just vary so
 * two pages rarely open alike.
 */
export const PAGE_DOODLES: Record<string, DoodleName> = {
  '': 'olive-sprig',
  about: 'olive-sprig',
  services: 'eucalyptus',
  process: 'eucalyptus',
  'e-design': 'leafy-stem',
  contact: 'berry-sprig',
  faq: 'leafy-stem',
  portfolio: 'berry-sprig',
};

/** The order the rest of the set follows. */
const ROTATION: DoodleName[] = ['berry-sprig', 'eucalyptus', 'olive-sprig', 'leafy-stem'];

/**
 * Most botanicals one page carries. Two keeps them a signature, not a
 * pattern; raise it here (and only here) if a page ever feels bare.
 */
export const MAX_DOODLES: number = 2;

/**
 * Which of `count` eligible sections get a botanical: spread as far apart as
 * the page allows, always starting with the first. With the default two, that
 * is the first and the last. Returned in page order, never more than
 * MAX_DOODLES.
 */
export function doodleSlots(count: number, max: number = MAX_DOODLES): number[] {
  if (count <= 0 || max <= 0) return [];
  if (count <= max) return Array.from({ length: count }, (_, i) => i);
  if (max === 1) return [0];
  return Array.from({ length: max }, (_, i) => Math.round((i * (count - 1)) / (max - 1)));
}

/** The first segment of a path: "/services/" -> "services", "/" -> "". */
export function firstSegment(path: string): string {
  const clean = (path.split(/[?#]/)[0] ?? '').replace(/^\/+|\/+$/g, '');
  return clean.split('/')[0] ?? '';
}

/** A stable small number from a string (FNV-1a). */
function hashOf(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619);
  return h >>> 0;
}

/**
 * The doodles for `count` sections of the page at `path`: the page's own
 * first, then the rotation from a page-specific starting point, skipping any
 * that would repeat the one before. Same page, same doodles, every build.
 */
export function doodlesForPage(path: string, count: number): DoodleName[] {
  const seg = firstSegment(path);
  const first = PAGE_DOODLES[seg] ?? ROTATION[hashOf(seg) % ROTATION.length]!;
  const out: DoodleName[] = [];
  let k = hashOf(`${seg}#`) % ROTATION.length;
  for (let i = 0; i < count; i++) {
    if (i === 0) {
      out.push(first);
      continue;
    }
    let next = ROTATION[k % ROTATION.length]!;
    k++;
    if (next === out[i - 1]) {
      next = ROTATION[k % ROTATION.length]!;
      k++;
    }
    out.push(next);
  }
  return out;
}
